#!/bin/sh
set -eu

: "${VERSION:?VERSION is required}"
: "${CNB_REPO_SLUG:?CNB_REPO_SLUG is required}"

branch="release/$VERSION"
git config user.name "cnb-ci"
git config user.email "cnb-ci@users.noreply.cnb.cool"
git switch -c "$branch"
git add CHANGELOG.md internal/config/version.go \
  ui/artalk/package.json docs/docs/code/ArtalkVersion.json
git commit -m "chore: release $VERSION"
git push --set-upstream origin "$branch"

body_file="$(mktemp)"
trap 'rm -f "$body_file"' EXIT
cat > "$body_file" <<EOF
## Release $VERSION

This PR was generated by the CNB release preparation pipeline.
Review the changelog and version files before merging.
EOF

cnb pulls post-pull \
  --repo "$CNB_REPO_SLUG" \
  --base master \
  --head "$branch" \
  --title "chore: release $VERSION" \
  --body-file "$body_file"
